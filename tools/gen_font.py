#!/usr/bin/env python3
"""Rasterise Liberation Mono to an 8x16 bitmap font (ASCII 0x20..0x7E, then Cyrillic U+0410..U+044F) -> font8x16.h"""
import sys
from PIL import Image, ImageDraw, ImageFont

FONT = "/usr/share/fonts/truetype/liberation/LiberationMono-Bold.ttf"
out = sys.argv[1]
font = ImageFont.truetype(FONT, 13)
rows = []
CODES = list(range(0x20, 0x7F)) + list(range(0x410, 0x450))
for code in CODES:
    im = Image.new("L", (8, 16), 0)
    ImageDraw.Draw(im).text((0, 0), chr(code), font=font, fill=255)
    glyph = []
    for y in range(16):
        b = 0
        for x in range(8):
            if im.getpixel((x, y)) >= 110:
                b |= 0x80 >> x
        glyph.append(b)
    if code == ord("0"):   # Liberation's dotted zero reads as 8 at this size: plain oval
        art = ["........"] * 2 + ["..####.."] + [".##..##."] * 6 + ["..####.."] + ["........"] * 6
        glyph = [int(r.replace(".", "0").replace("#", "1"), 2) for r in art]
    rows.append(glyph)
with open(out, "w") as f:
    f.write("/* Generated by tools/gen_font.py (Liberation Mono Bold 13px) - do not edit.\n   Index 0..94: ASCII 0x20..0x7E; 95..158: Cyrillic U+0410..U+044F. */\n")
    f.write("#ifndef FONT8X16_H\n#define FONT8X16_H\n#include <stdint.h>\n")
    f.write("static const uint8_t font8x16[159][16] = {\n")
    for code, g in zip(CODES, rows):
        f.write("    {" + ",".join("0x%02x" % b for b in g) + "}, /* %r */\n" % chr(code))
    f.write("};\n#endif\n")
